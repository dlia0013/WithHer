export const getProviderById = (id) =>
  providers.find((p) => String(p.id) === String(id))

export function providersToGeoJSON(list = providers) {
  return {
    type: 'FeatureCollection',
    features: list
      .filter(
        (p) =>
          Array.isArray(p.coords) &&
          p.coords.length === 2 &&
          typeof p.coords[0] === 'number' &&
          typeof p.coords[1] === 'number'
      )
      .map((p) => ({
        type: 'Feature',
        geometry: { type: 'Point', coordinates: p.coords },
        properties: {
          id: p.id,
          name: p.name,
          type: p.type,
          suburb: p.suburb,
          postcode: p.postcode,
          address: p.address,
          phone: p.phone || '',
          bulk_billing: p.bulk_billing,
          telehealth: p.telehealth,
          languages: p.languages || [],
        },
      })),
  }
}